/// **THE INDEX'S TOKEN CHARACTERS** (VX-955 — the VX-980 run, batch 1;
/// `notes/plans/fixes/vx-980-search-fixes.md`). A typed word is asked of the
/// search index exactly when the INDEX would find a token in it. A word the
/// index finds no token in would be an FTS5 phrase holding nothing — it
/// matches no row, and ANDed beside real words it empties the whole answer
/// (`red +` found nothing while `red` found the note).
///
/// The index's tokenizer is the one its DDL names — `search_fts` in
/// `Persistence/SearchIndex.swift`, `unicode61 remove_diacritics 2` with its
/// default token categories — as LINKED: SQLCipher's prebuilt FTS5 (measured
/// on SQLite 3.53.4 inside SQLCipher 4.18.0). Its category table is SQLite's
/// own, never the OS's Unicode, and the two differ: symbols (`+ $ © ™ ∞`, 😀
/// U+1F600), combining marks, the zero-width joiner and the variation
/// selectors SEPARATE; letters, numbers (`½ ²`) and private use are TOKENS;
/// and every scalar SQLite's table does not know — unassigned at the Unicode
/// version it was built from, 🙂 U+1F642 among them — is a TOKEN (its default
/// category). Unicode's general categories alone cannot say that, and the
/// prebuilt binary carries no source table to port, so the set is MEASURED
/// from the linked tokenizer, one scalar at a time, and held here as its
/// transition points. `SearchTokenizerSweepTests` re-measures EVERY scalar
/// against the tokenizer built from the live DDL and fails, printing the
/// re-measured table, the moment the link or the DDL moves (a SQLCipher bump,
/// a migration that changes the options).
///
/// A WORD holds a token exactly when one of its scalars is a token character:
/// `unicode61` begins a token at the first token character, and a combining
/// mark only ever continues one (pinned word by word in the same suite —
